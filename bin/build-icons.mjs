// Builds the icon subset used by ENLIXO Tutor from the Solar icon set (Iconify, MIT).
//   npm i --no-save @iconify-json/solar   (anywhere)
//   node bin/build-icons.mjs path/to/@iconify-json/solar/icons.json
// Writes assets/icons/icons.json (for PHP: enlixo_icon()) and assets/js/enlixo/core/icon-data.js (for JS: icon()).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const set = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const map = JSON.parse(readFileSync(join(root, 'assets/icons/icon-map.json'), 'utf8'));
const out = {};
for (const [name, solar] of Object.entries(map)) {
  if (name.startsWith('_')) continue;
  const icon = set.icons[solar] ?? set.icons[set.aliases?.[solar]?.parent];
  if (!icon) throw new Error(`Solar has no icon "${solar}" (for "${name}")`);
  out[name] = icon.body;
}
const json = JSON.stringify(out);
writeFileSync(join(root, 'assets/icons/icons.json'), json + '\n');
writeFileSync(join(root, 'assets/js/enlixo/core/icon-data.js'), `// Generated by bin/build-icons.mjs from assets/icons/icon-map.json (Solar icons, MIT). Do not edit.\nexport const ICONS = ${json};\n`);
console.log(`${Object.keys(out).length} icons written`);
